"""Generate a dbt ``schema.yml`` with tests inferred from the data."""

from __future__ import annotations

from datasniff.profile import TableProfile


def _sq(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _test_block(name: str, args: dict[str, str], new_syntax: bool, indent: str) -> list[str]:
    lines = [f"{indent}- {name}:"]
    inner = indent + "    "
    if new_syntax:  # dbt >= 1.10 nests test arguments under `arguments:`
        lines.append(f"{inner}arguments:")
        inner += "  "
    lines += [f"{inner}{k}: {v}" for k, v in args.items()]
    return lines


def schema_yml(profile: TableProfile, model: str, new_syntax: bool = False) -> str:
    lines = [
        "version: 2",
        "",
        "models:",
        f"  - name: {model}",
        f'    description: "Generated by datasniff from {profile.source} ({profile.rows:,} rows)."',
        "    columns:",
    ]
    for col in profile.columns:
        lines.append(f"      - name: {col.name}")
        lines.append(f"        data_type: {col.dtype.lower()}")
        if col.flags:
            lines.append(f'        description: "datasniff flags: {", ".join(col.flags)}"')
        tests: list[str] = []
        if col.nulls == 0 and col.non_null > 0:
            tests.append("          - not_null")
        if "unique" in col.flags:
            tests.append("          - unique")
        if "categorical" in col.flags and col.all_values and col.dtype.upper() != "BOOLEAN":
            if col.is_numeric:
                args = {"values": "[" + ", ".join(col.all_values) + "]", "quote": "false"}
            else:
                # Trim and de-duplicate so the test encodes the *intended* values: dirty variants
                # like " shipped" then fail the test instead of being baked into it.
                values = sorted({v.strip() for v in col.all_values})
                args = {"values": "[" + ", ".join(_sq(v) for v in values) + "]"}
            tests += _test_block("accepted_values", args, new_syntax, "          ")
        if tests:
            lines.append("        data_tests:")
            lines += tests
    return "\n".join(lines) + "\n"
